"""Rows without the MRF keyword generate exactly what the release before the stage did.

``tests/data/precursor_off_golden.json`` holds the batch script and the planned configuration
files of five rows without the keyword, generated by the library as it was before the stage
existed (run ``python test_precursor_off_identity.py <output>`` against that tree to rebuild
it). The test regenerates them and compares every byte.
"""

from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

import test_restart_in_job as t

GOLDEN = Path(__file__).resolve().parents[1] / "data/precursor_off_golden.json"
SLIDING = '[sliding]\nzones = 2\nrotating_zone = 0\ninterface = ["X_OUT", "X_IN"]\n'
APP = ' / hpc.application_id: "tools/su2.sh"'
EXPORT = " / EXPORT_UNSTEADY_LAST_ITER: 9"
SKIP = {"job.exit", "stdout.log", "stderr.log"}


def dump(root: Path) -> dict[str, str]:
    found = {}
    for path in sorted((root / "sims").rglob("*")):
        if not path.is_file() or path.is_symlink() or path.name in SKIP:
            continue
        if path.name.startswith(("submit", "fake-submit")) or path.suffix == ".su2":
            continue
        text = path.read_text(errors="replace").replace(root.as_posix(), "<ROOT>")
        found[path.relative_to(root).as_posix()] = text
    return found


def scenario(root: Path, rows, setup="", pair=False) -> dict[str, str]:
    t.build(root, rows, setup=setup)
    if pair:
        source = t.source_id_for(root)
        t.write_matrix(
            root,
            [t.row(7001, "qsteady_rotor"), t.row(7002, "unsteady_rotor", t.CLOCK, source)],
        )
    assert t.batch(root, command="plan") == 0
    assert t.batch(root) == 0
    return dump(root)


def render_all(base: Path) -> dict[str, dict[str, str]]:
    cases = {
        "steady_with_wrapper": ([t.row(7001, "qsteady_rotor", "-", "-")], "", False),
        "sliding_with_wrapper": (
            [t.row(7001, "unsteady_rotor", t.CLOCK + APP, "-")],
            SLIDING,
            False,
        ),
        "sliding_with_export_window": (
            [t.row(7001, "unsteady_rotor", t.CLOCK + EXPORT, "-")],
            SLIDING,
            False,
        ),
        "sliding_with_export_window_and_wrapper": (
            [t.row(7001, "unsteady_rotor", t.CLOCK + EXPORT + APP, "-")],
            SLIDING,
            False,
        ),
        "restart_pair_in_one_batch": ([t.row(7001, "qsteady_rotor")], "", True),
    }
    found = {}
    for name, (rows, setup, pair) in cases.items():
        root = base / name
        root.mkdir()
        found[name] = scenario(root, rows, setup, pair)
    return found


def test_rows_without_the_keyword_render_as_before(tmp_path):
    golden = json.loads(GOLDEN.read_text(encoding="utf-8"))
    found = render_all(tmp_path)
    assert sorted(found) == sorted(golden)
    for name in golden:
        assert found[name] == golden[name], name


def test_the_golden_files_hold_no_precursor_file():
    golden = json.loads(GOLDEN.read_text(encoding="utf-8"))
    names = [path for files in golden.values() for path in files]
    assert names and not any("precursor" in n or "run_mrf" in n for n in names)


if __name__ == "__main__":
    with tempfile.TemporaryDirectory(dir=sys.argv[2] if len(sys.argv) > 2 else None) as folder:
        Path(sys.argv[1]).write_text(
            json.dumps(render_all(Path(folder)), indent=1, sort_keys=True) + "\n",
            encoding="utf-8",
            newline="\n",
        )
